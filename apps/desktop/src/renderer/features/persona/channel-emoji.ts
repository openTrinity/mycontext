/**
 * 官方默认包里**刻意不映射**的那些。这个常量存在的意义是
 * "记下我们知道它是表情、但决定不转" —— 免得下次有人以为是漏了。
 *
 * · `二哈` `狗子` `钉钉` `三多` —— 平台自有形象，没有 Unicode 对应物；
 * · `对勾` —— 更像排版符号（`✓`）而不是表情，转了会让列表很花；
 * · `KPI` —— 企业语境的文字表情，emoji 里没有对应物。
 *
 * ★ 它们**不在** `CHANNEL_EMOJI` 里，所以行为上等同于"不认识" ——
 * 原样显示 `[二哈]`。用户看到方括号就知道那是个没转的表情，
 * 这比给一个语义错的 emoji 诚实。
 */
export const UNMAPPED_OFFICIAL: readonly string[] = ["二哈", "狗子", "钉钉", "三多", "对勾", "KPI"]

/**
 * 把正文里认识的表情标记换成 emoji。
 *
 * ★ 只替换**表里有**的：正则先匹配 `[xx]` 的形状，再查表 —— 查不到就
 * 原样返回那一段。这样"没收录的表情"与"用户自己打的方括号"都不会被动。
 *
 * ★ 不递归、不处理嵌套：`[[赞]]` 会得到 `[👍]`，那是可接受的
 * （嵌套方括号在真实数据里没出现过，而为它加复杂度不值得）。
 */
export function replaceChannelEmoji(text: string): string {
  /**
   * 长度上限 8：官方名最长是 `生日快乐`（4 字），`100分` 这类含数字的也在内；
   * 给到 8 覆盖英文名（`KPI`）而不至于吞掉整句话。
   */
  return text.replace(/\[([^[\]]{1,8})\]/g, (whole, name: string) => {
    return CHANNEL_EMOJI[name] ?? whole
  })
}
