/**
 * 渠道表情标记 → Unicode emoji。
 *
 * ## ★ 为什么需要它
 *
 * 渠道把表情存成 `[天使]` 这样的**本地化文本标记**，落库时原样保留
 * （那是对的：原文可回溯）。但界面上直接显示 `[天使]` 与钉钉 App 里
 * 看到的完全不同 —— 用户要在两个界面之间对照同一段对话时，
 * 满屏方括号会让他读不下去。
 *
 * 实测本 vault：含 `[xx]` 的消息 15966 条，去掉图片/文件那类协议标记后
 * 仍有几千条是真表情。
 *
 * ## ★★ 为什么是**白名单**而不是"凡是 [xx] 都转"
 *
 * 实测那 15966 条里的 `[xx]` 有 **610 种**，其中大量**不是**表情：
 *
 * ```
 * [图片消息] [文件] [image]        —— 协议标记（另有清洗规则处理）
 * [FIRING:1] [RESOLVED] [告警]    —— 监控机器人的状态词
 * [点击查看详情] [戳这里]          —— 卡片里的按钮文案
 * [必填] [选填] [问题描述]         —— 表单模板的字段名
 * [某某某]                        —— ★ 有人把**真实姓名**写进方括号
 * ```
 *
 * 无脑转的后果：告警群的 `[FIRING:1]` 变成一个笑脸，而值班的人会漏掉它。
 * 所以只转**明确认识**的那些，其余原样留着 —— 留着是诚实的（那本来就是
 * 用户打的字），而错转是不可逆的误导。
 *
 * ## ★ 这张表**手写**，不从本机数据自动生成
 *
 * 我一开始想按"纯中文 1-4 字且出现≥3 次"从库里筛，筛出来 138 条里
 * 混着**四个真实同事姓名**（他们把名字写在方括号里）。那份清单一旦入库
 * 就是一次不可撤回的泄漏（CLAUDE.md §1.1）。
 *
 * 所以：清单是照**钉钉官方表情名**手写的；本机数据只用来验证覆盖率，
 * 不用来生成内容。
 *
 * ## 映射到哪个 emoji
 *
 * 取语义最近的标准 emoji，而不是追求像素级还原 —— 后者做不到
 * （渠道自有表情没有 Unicode 对应物，如"二哈""狗子"这类平台特有的）。
 * 对不上的**不进表**：显示 `[二哈]` 比显示一个语义错的 emoji 好，
 * 因为前者用户知道那是个表情，后者会让他以为对方真的发了那个意思。
 */

