/**
 * VAULT v26 — 把**占位会话名**清成 NULL。
 *
 * ## ★★ 为什么这不只是"改个显示"
 *
 * 飞书的单聊在消息搜索响应里没有会话名（`chat_partner` 只有 open_id，
 * `chat_name` 在 p2p 上压根不存在）。解析层原来推不出名字时写一个占位字符串
 * 进库 —— 而落库那侧是：
 *
 * ```sql
 * title = COALESCE(excluded.title, conversations.title)
 * ```
 *
 * 占位是**非 NULL** 的，所以它有两个后果：
 *
 * ① **它会覆盖掉已经拿到的真名。** 同一个会话在下一页/下一轮里恰好只有
 *    我自己发言时，那次 upsert 就把名字冲回占位了。解析层那句"已有名字优先"
 *    只在单页内成立（那是一个 per-page 的 Map），跨轮次不成立 ——
 *    而跨轮次才是常态。
 * ② **改好推导也救不回存量行。** 新逻辑给 NULL 时 `COALESCE` 会保留旧值，
 *    而旧值正是占位 —— 于是那些会话**永远**显示占位，除非有人手动清。
 *
 * 实测：本机飞书库 4 个单聊全是占位，用户在采集范围里看到四行一模一样的
 * 名字，完全没法勾选。
 *
 * 所以解析层改成给 NULL（见 `parseLarkMessagePage`），而存量那批要在这里清掉。
 *
 * ## ★ 判据是"等于那个占位串"，而不是"像占位"
 *
 * 只清 `'飞书会话'` 这一个确切值。不做模糊匹配（比如"含『会话』二字"）——
 * 真实群名里完全可能有这两个字，而误清一个真名是不可逆的信息丢失
 * （下一轮采集能不能拿回来取决于那个会话这段时间有没有对端发言）。
 *
 * ## ★ 为什么不顺手把名字补上
 *
 * 补名字要读 `messages.sender_display_name` 并判"哪个发送者不是我"，
 * 而"我是谁"在这张表里可能还没有（`channel_self_identity` 为空是常态 ——
 * 那正是同一批修复里的另一条）。迁移不该依赖一个可能缺失的前置状态。
 * 清成 NULL 之后，下一轮采集会用新推导填上真名；在那之前界面显示
 * id 尾段（每行不同，至少可区分）。
 */
export const VAULT_0026_CLEAR_PLACEHOLDER_TITLES = `
UPDATE conversations SET title = NULL WHERE title = '飞书会话';
`
