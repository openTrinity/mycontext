/**
 * VAULT v31 — **重判**被误记成「保密会话」的那些会话。
 *
 * ## ★★★ 它修的是一次**归因错误**，不是数据损坏
 *
 * `markUnreadable` 原来按**错误码**归因：所有 `RESOURCE_FORBIDDEN` 都记成
 * `confidential`（保密会话）。而上游把 `server_error_code=1001` 复用于
 * 至少三件完全不同的事：
 *
 * | 服务端文案 | 真正的含义 | 有没有补救 |
 * |---|---|---|
 * | `该群为保密群` | 对方设了保密 | 无 |
 * | `org not match` | 资源属于另一个组织 | 换 profile |
 * | ★ `peerUid is required` | **我们没有这个单聊要的标识** | 无（userId 要走花名册，§5 不许） |
 *
 * 实测本机库：**33 个单聊**被标成 `confidential`，而它们全都有对端
 * openId、格式正常、以前也读得到 —— 拿真实 openId 直接跑渠道 CLI 复现过。
 *
 * ★ 那些会话**确实读不了**（结果是对的），错的是**为什么读不了**。
 * 而归因错的代价很具体：界面照它说话会让用户去问对方"你是不是设了保密"，
 * 而问题在我们这边。
 *
 * ## ★★★ 为什么是「清掉标记」而不是「改写成新 reason」
 *
 * 这个迁移**不可能**知道当初那 33 行各自是哪一种 —— 库里只存了
 * `confidential` 这个结论，原始错误文案没留。
 *
 * 所以正确做法是**把结论清掉、让它重新判一次**：
 *
 * ```
 * 清掉 unreadable_reason
 *   → 下一轮定向补拉会再试一次（每个会话一次请求）
 *   → 新的分类层按文案细分 → 落一个正确的 reason
 * ```
 *
 * ★ 代价是**一次**多余的失败请求（每个受影响会话一次），而不是每 2 分钟
 * 一次 —— 因为新代码仍然会把它们标回不可读，只是 reason 是对的。
 * 那点配额换一份正确的归因，值得。
 *
 * ★★ 而且它**自愈**：万一某个会话其实已经能读了（比如对方取消了保密、
 * 或我们重新加入了那个群），清掉标记正好让它恢复采集 ——
 * 改写 reason 反而会把"永久跳过"这个状态固化下来。
 *
 * ## ★ 只清 `confidential`，不动其余
 *
 * `cross_org` 那些是另一条路径（`PERMISSION_REQUIRED`）标的，
 * 它的归因一直是对的（授权一次就能读）。清它只会白烧一次请求。
 *
 * ★★ 也**不动** `unreadable_at`：那一列记的是"什么时候发现读不了的"，
 * 清 reason 之后它是一个孤立的时间戳 —— 但留着它有诊断价值
 * （"这个会话上次被判不可读是三天前"），而清掉它等于丢信息。
 * 下次真的标记时它会被一起刷新。
 */
export const VAULT_0031_REJUDGE_UNREADABLE = `
-- 清掉「保密会话」这个结论，让下一轮重新判一次并落正确的 reason。
--
-- ★ 只清 confidential：cross_org 的归因一直是对的（见文件头）。
-- ★★ 不加 channel_id 条件：这个误判与渠道无关（分类层是共用的），
--    而每个 vault 只有一个主渠道 + 若干 source 库，各自跑自己的迁移。
UPDATE conversations
   SET unreadable_reason = NULL
 WHERE unreadable_reason = 'confidential';
`
